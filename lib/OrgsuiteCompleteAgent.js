  /**
   * Build STRONG Netscape session cookie file
   * @param {Object} cookies - { name: value }
   * @param {string} domain - e.g. ".github.com"
   * @returns {string} ready-to-import cookie.txt content
   */
  buildStrongNetscapeCookie(cookies = {}, domain = ".example.com") {
    const lines = [
      "# Netscape HTTP Cookie File",
      "# Orgsuite STRONG Company Cookies – Session only",
      "# Generated by OrgsuiteCompleteAgent v2.0"
    ];

    for (const [name, value] of Object.entries(cookies)) {
      // domain | includeSubdomains | path | secure | expiry(0=session) | name | value
      lines.push(`${domain}\tTRUE\t/\tTRUE\t0\t${name}\t${value}`);
    }
    return lines.join("\n");
  },

  /**
   * Build a secure Cookie header (alternative to file import)
   */
  buildSecureCookieHeader(cookies = {}) {
    const parts = Object.entries(cookies).map(([k, v]) => `${k}=${v}`);
    return `Cookie: ${parts.join("; ")}`;
  },

